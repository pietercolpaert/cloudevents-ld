// Generates examples/*/events.ttl from examples/*/events.json by applying JSON-LD contexts:
// always the repository's context.jsonld, followed by the example's own context.jsonld
// (for producer-specific extension attributes) when the example has one.
import { access, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import jsonld from 'jsonld';
import { Parser, Writer } from 'n3';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const examplesDir = path.join(root, 'examples');

const readJson = async (file) => JSON.parse(await readFile(file, 'utf8'));
const exists = (file) => access(file).then(() => true, () => false);

// Turtle prefixes: every context term that maps to a namespace IRI (ending in # or /).
function prefixesOf(contexts) {
  const prefixes = { rdf: 'http://www.w3.org/1999/02/22-rdf-syntax-ns#' };
  for (const context of contexts) {
    for (const [term, value] of Object.entries(context)) {
      if (!term.startsWith('@') && typeof value === 'string' && /[#/]$/.test(value)) prefixes[term] = value;
    }
  }
  return prefixes;
}

function toTurtle(nquads, prefixes, header) {
  const writer = new Writer({ prefixes });
  writer.addQuads(new Parser({ format: 'N-Quads', blankNodePrefix: '' }).parse(nquads));
  return new Promise((resolve, reject) =>
    writer.end((error, turtle) => (error ? reject(error) : resolve(header + turtle))));
}

const mainContext = (await readJson(path.join(root, 'context.jsonld')))['@context'];
const folders = (await readdir(examplesDir, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

for (const folder of folders) {
  const dir = path.join(examplesDir, folder);
  const input = path.join(dir, 'events.json');
  if (!(await exists(input))) continue;

  const contexts = [mainContext];
  const contextFiles = ['../../context.jsonld'];
  const localContext = path.join(dir, 'context.jsonld');
  if (await exists(localContext)) {
    contexts.push((await readJson(localContext))['@context']);
    contextFiles.push('context.jsonld');
  }

  const nquads = await jsonld.toRDF(await readJson(input), {
    expandContext: { '@context': contexts },
    // No base IRI: a relative dataref or dataschema is dropped instead of being resolved
    // against a processor-specific default (pyld, for example, uses http://example.org/base/).
    base: null,
    format: 'application/n-quads',
  });
  const header = `# Generated by scripts/build-examples.js from events.json with ${contextFiles.join(', ')}.\n# Do not edit: change the JSON or the contexts and rebuild with \`npm run build:examples\`.\n\n`;
  await writeFile(path.join(dir, 'events.ttl'), await toTurtle(nquads, prefixesOf(contexts), header));
  console.log(`examples/${folder}/events.ttl  (${nquads.trim().split('\n').length} triples; ${contextFiles.join(' + ')})`);
}
